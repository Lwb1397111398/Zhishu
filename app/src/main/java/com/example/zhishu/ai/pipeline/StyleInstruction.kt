package com.example.zhishu.ai.pipeline

import com.example.zhishu.domain.model.GENRE_AUTO

/**
 * 章节规划阶段注入的风格指令（问题6）。
 *
 * 用户指出：像民法这种学科，他根本不知道该选什么小说风格。
 * 强迫用户选风格是把设计负担推给了不懂的人，选错了还会拖累效果
 * （给民法配"武侠"，很容易写成主角在江湖里背法条）。
 *
 * 所以默认提供「AI 自由发挥」：由模型按学科性质自选叙事载体，
 * 并在故事总纲里写清选它的理由（approach），再回填到项目上。
 */
internal object StyleInstruction {

    fun of(genre: String): String =
        if (genre.isBlank() || genre == GENRE_AUTO) AUTO else fixed(genre)

    private val AUTO = """
        **风格由你自己决定。** 用户没有指定，因为他也不确定这门学科适合怎么讲——这恰恰是你该做的判断。

        先想清楚：这门学科的知识是靠什么长出来的？
        - 靠"一个人在生活中不断遇到新麻烦"长出来的（民法、经济学、社会学），适合跟着一个人的一生往前走，制度随着他的处境自己出现。
        - 靠"一代代人推翻前人"长出来的（物理、哲学、数学），适合沿着思想史走，让读者站在当时的困惑里，和当年的人一起想不通、再一起想通。
        - 靠"系统一层层搭起来"长出来的（计算机、工程、医学），适合从最小的能跑起来的东西开始，一层层往上加，每加一层都因为下一层顶不住了。
        - 靠"在具体冲突里被反复检验"长出来的（法律实务、管理、历史），适合围绕一个真正棘手的处境展开。

        选定之后在 `approach` 里写清你为什么这样选。**不要为了热闹硬套一个类型**：
        如果这门学科最自然的讲法就是"跟着一个普通人的生活往前走"，那就这样写，不需要加悬疑、玄幻或者穿越。
        载体的唯一标准是：让制度自己长出来最省力。
    """.trimIndent()

    private fun fixed(genre: String): String = """
        用户指定的风格是：**$genre**。请以此为叙事载体。

        但要守住一条底线：风格服务于理解，不能反过来喧宾夺主。
        如果某处为了迎合风格就得歪曲知识、或者要靠角色大段背书才能把话讲完，
        那就把风格收淡一些，优先保证推演走得通。在 `approach` 里写清你怎么让 $genre 承载这门学科。
    """.trimIndent()
}
